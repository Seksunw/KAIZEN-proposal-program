let currentLang = 'th';

export function initLang() {
  let lang = 'th';
  try { lang = localStorage.getItem('kaizen_lang') || 'th'; } catch { /* private mode */ }
  currentLang = DICT[lang] ? lang : 'th';
  return currentLang;
}

export function setLang(lang) {
  currentLang = DICT[lang] ? lang : 'th';
  try { localStorage.setItem('kaizen_lang', currentLang); } catch { /* private mode */ }
}

export function getLang() {
  return currentLang;
}

export function t(key) {
  return DICT[currentLang]?.[key] ?? DICT.th[key] ?? key;
}

// ★ ใหม่ (i18n audit Round 12/13 — full project translation pass) — t() เป็นแค่ lookup ตรงๆ
// ไม่รองรับ interpolation เลย ข้อความที่มีค่าแทรก (จำนวนตัวอักษร/วันที่/ชื่อ ฯลฯ) ใช้ตัวนี้แทน
// เขียนคีย์เป็น '...{name}...' แล้วส่ง vars = { name: value } เข้ามาแทนที่ทุกจุดที่ match
export function tf(key, vars = {}) {
  let s = t(key);
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
